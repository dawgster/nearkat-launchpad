/** A kat's nature, one line per trait, in a fixed order. */
export function natureOf(kat: KatLook): string[] {
  return (Object.keys(NATURES) as Array<keyof KatLook>).map((layer) => {
    const line = NATURES[layer][kat[layer]];
    if (!line) {
      throw new Error(`No nature for ${layer} "${kat[layer]}"`);
    }
    return line;
  });
}
